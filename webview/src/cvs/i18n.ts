export function cvsT(
  language: string | undefined,
  key: keyof typeof cvsEn,
): string {
  const normalized = language?.toLowerCase();
  const dictionary =
    normalized === "zh" || normalized === "zh-cn" || normalized === "zh-tw"
      ? cvsZhCn
      : cvsEn;
  return dictionary[key] ?? cvsEn[key] ?? dictionary.unknown;
}
